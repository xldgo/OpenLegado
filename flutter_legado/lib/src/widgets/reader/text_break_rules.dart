/// 初次断行、溢出回退及段末行内元素共用的断点规则。
class TextBreakRules {
  static const closing = {
    '！',
    '，',
    '。',
    '、',
    '；',
    '：',
    '？',
    '”',
    '’',
    '）',
    '］',
    '｝',
    '》',
    '〉',
    '〕',
    '】',
    '〗',
    '」',
    '』',
    '﹂',
    '﹄',
    '…',
    '—',
    '～',
    '·',
    '〃',
    '!',
    ',',
    '.',
    ':',
    ';',
    '?',
    ')',
    ']',
    '}',
    '>',
    "'",
    '"',
  };
  static const opening = {
    '“',
    '‘',
    '（',
    '［',
    '｛',
    '《',
    '〈',
    '〔',
    '【',
    '〖',
    '『',
    '「',
    '﹁',
    '﹃',
    '(',
    '[',
    '{',
    '<',
    '‹',
    "'",
    '"',
  };
  static final _latin = RegExp(
    r"^[A-Za-z0-9\u00c0-\u024f\u1e00-\u1eff\u0300-\u036f'’]+$",
    unicode: true,
  );
  static bool forbidden(String previous, String next) =>
      closing.contains(next) || opening.contains(previous);
  static bool insideWord(String previous, String next) =>
      _latin.hasMatch(previous) && _latin.hasMatch(next);
}
